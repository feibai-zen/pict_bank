def add_two_num(a, b):
    """
    计算两个数字的和
    
    参数:
        a (int/float): 第一个数字
        b (int/float): 第二个数字
    
    返回:
        int/float: 两个数字的和
    """
    return a + b


def concat_two_str(a, b):
    """
    拼接两个字符串

    参数:
        a (str): 第一个字符串
        b (str): 第二个字符串

    返回:
        str: 拼接后的字符串
    """
    return a + b
